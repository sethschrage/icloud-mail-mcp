# user that Dovecot services + mail files run as
resolve_run_user() {
  if [[ "$(id -u)" == "0" ]]; then
    RUN_USER="${TEST_MAIL_USER:-vmail}"
    if ! getent passwd "$RUN_USER" >/dev/null; then
      log "creating system user '$RUN_USER' for mail storage"
      useradd --system --no-create-home --home-dir /nonexistent --shell /usr/sbin/nologin "$RUN_USER" \
        || die "could not create user $RUN_USER"
    fi
  else
    RUN_USER="$(id -un)"
  fi
  RUN_GROUP="$(id -gn "$RUN_USER")"
}

proc_alive() { # $1 = pid; true if it exists and is not a zombie
  local pid="$1" state
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  kill -0 "$pid" 2>/dev/null || return 1
  if [[ -r "/proc/$pid/stat" ]]; then
    state="$(sed -E 's/^[0-9]+ \(.*\) ([A-Za-z]).*/\1/' "/proc/$pid/stat" 2>/dev/null)"
  else
    state="$(ps -o stat= -p "$pid" 2>/dev/null | tr -d ' ')"
  fi
  [[ -n "$state" && "$state" != Z* ]]
}

pid_alive() { # $1 = pidfile
  [[ -s "$1" ]] || return 1
  proc_alive "$(tr -d '[:space:]' < "$1")"
}

port_open() { # $1 = port
  (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
}

wait_port() { # $1 = port, $2 = label, $3 = timeout seconds
  local port="$1" label="$2" timeout="${3:-20}" i=0
  while ! port_open "$port"; do
    i=$((i + 1))
    if (( i > timeout * 10 )); then
      die "$label did not open port $port within ${timeout}s (see $LOG_DIR)"
    fi
    sleep 0.1
  done
  log "$label is accepting connections on 127.0.0.1:$port"
}

wait_port_closed() { # $1 = port, $2 = label, $3 = timeout seconds
  local port="$1" label="$2" timeout="${3:-20}" i=0
  while port_open "$port"; do
    i=$((i + 1))
    if (( i > timeout * 10 )); then
      log "WARNING: $label still listening on $port after ${timeout}s"
      return 1
    fi
    sleep 0.1
  done
}

render_dovecot_conf() {
  local tmp="$DOVECOT_CONF.tmp.$$"
  # The instance paths are substituted before @ROOT@ so they may themselves live under ROOT.
  local -a sed_args=(
    -e "s#@INSTANCE_NAME@#$DOVECOT_INSTANCE#g" -e "s#@BASE_DIR@#$DOVECOT_BASE_DIR#g"
    -e "s#@STATE_DIR@#$DOVECOT_STATE_DIR#g" -e "s#@LOG_FILE@#$DOVECOT_LOG#g" -e "s#@MAIL_DIR@#$MAIL_DIR#g"
    -e "s#@ROOT@#$ROOT#g" -e "s#@RUN_USER@#$RUN_USER#g" -e "s#@RUN_GROUP@#$RUN_GROUP#g"
    -e "s#@IMAP_PORT@#$IMAP_PORT#g" -e "s#@IMAPS_PORT@#$IMAPS_PORT#g"
  )
  if [[ "$DOVECOT_STRIP_SPECIAL_USE" == "yes" ]]; then
    sed_args+=(-e '/^[[:space:]]*special_use[[:space:]]*=/d')
  fi
  mkdir -p "$(dirname "$DOVECOT_CONF")"
  sed "${sed_args[@]}" "$DOVECOT_TMPL" > "$tmp"
  if grep -q '@[A-Z][A-Z_]*@' "$tmp"; then
    rm -f "$tmp"
    die "unsubstituted placeholder left in the rendered config (template newer than scripts/common.sh?)"
  fi
  {
    echo "## GENERATED by $DOVECOT_CONF_ORIGIN from dovecot.conf.tmpl on $(date -u +%Y-%m-%dT%H:%M:%SZ) - edit the template instead."
    cat "$tmp"
    if [[ -n "$DOVECOT_EXTRA_CONF" ]]; then
      printf '\n%s\n' "$DOVECOT_EXTRA_CONF"
    fi
  } > "$DOVECOT_CONF"
  rm -f "$tmp"
}

# ---------------------------------------------------------------- profile selection
# Profile names are the basenames of dovecot/profiles/*.env ("main" is the default instance).
known_profiles() {
  local f
  for f in "$PROFILE_DEF_DIR"/*.env; do
    [[ -e "$f" ]] || continue
    basename "$f" .env
  done
}

# Parses `--profile NAME` / `--profile=NAME` out of "$@".
# Sets PROFILE_SEL (empty when not given, or "main") and PROFILE_REST_ARGS (all other arguments).
parse_profile_args() {
  PROFILE_SEL=""
  PROFILE_REST_ARGS=()
  while (($#)); do
    case "$1" in
      --profile)
        [[ $# -ge 2 && -n "$2" ]] || die "--profile needs a value: main, all, or one of: $(known_profiles | tr '\n' ' ')"
        PROFILE_SEL="$2"
        shift 2
        ;;
      --profile=*)
        PROFILE_SEL="${1#--profile=}"
        [[ -n "$PROFILE_SEL" ]] || die "--profile needs a value: main, all, or one of: $(known_profiles | tr '\n' ' ')"
        shift
        ;;
      *)
        PROFILE_REST_ARGS+=("$1")
        shift
        ;;
    esac
  done
  if [[ "$PROFILE_SEL" == "main" ]]; then
    PROFILE_SEL=""
  fi
}
