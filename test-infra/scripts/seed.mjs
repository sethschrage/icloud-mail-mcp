#!/usr/bin/env node
// Resets the test mailbox over IMAP and APPENDs the deterministic fixture set.
//
//   node scripts/seed.mjs            # clean + seed, writes fixtures/manifest.json
//   node scripts/inventory.mjs       # print fixtures/manifest.json as Markdown tables
//
// For exact, reproducible UIDs (1..N per mailbox) run ./reset.sh, which wipes the Maildir first.
// Running seed.mjs alone against a used mailbox still yields the same messages/flags, but UIDs
// continue from the previous UIDNEXT (a warning is printed and the manifest has the real UIDs).
//
// Env: IMAP_HOST (127.0.0.1) IMAP_PORT (1143) IMAP_SECURE (0) IMAP_USER (testuser) IMAP_PASS (app-specific-pass)
//      SEED_MANIFEST (fixtures/manifest.json) where to write the manifest; scripts/profiles.sh points it at
//                    run/profiles/<name>/manifest.json so seeding a profile never rewrites the main manifest
//      SEED_LABEL (seed) log prefix
// Needs no MOVE, SPECIAL-USE or LIST-EXTENDED (the iCloud-fidelity profiles lack them). It does read UIDs from
// APPENDUID, which Dovecot sends even when UIDPLUS is not advertised (profile no-uidplus).
import { ImapFlow } from 'imapflow';
import { simpleParser } from 'mailparser';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildFixtures, MAILBOXES, ACCOUNT } from './fixtures.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = process.env.SEED_MANIFEST ? path.resolve(process.env.SEED_MANIFEST) : path.join(ROOT, 'fixtures', 'manifest.json');
const TAG = `[${process.env.SEED_LABEL || 'seed'}]`;

const cfg = {
    host: process.env.IMAP_HOST || '127.0.0.1',
    port: Number(process.env.IMAP_PORT || 1143),
    secure: ['1', 'true', 'yes'].includes(String(process.env.IMAP_SECURE || '0').toLowerCase()),
    auth: { user: process.env.IMAP_USER || 'testuser', pass: process.env.IMAP_PASS || 'app-specific-pass' },
    tls: { rejectUnauthorized: false },
    logger: false,
    disableAutoIdle: true
};

const SPECIAL = Object.entries(MAILBOXES).filter(([, v]) => v.auto).map(([k]) => k);

function headerValue(raw, name) {
    const head = raw.split('\r\n\r\n')[0].replace(/\r\n[ \t]+/g, ' ');
    const m = new RegExp(`^${name}:\\s*(.*)$`, 'mi').exec(head);
    return m ? m[1].trim() : null;
}

async function main() {
    const client = new ImapFlow(cfg);
    await client.connect();

    // ---------------------------------------------------------------- 1. clean
    const existing = await client.list();
    const userFolders = existing
        .map(f => f.path)
        .filter(p => !SPECIAL.includes(p))
        .sort((a, b) => b.split('/').length - a.split('/').length || b.localeCompare(a)); // children first
    for (const p of userFolders) {
        try {
            await client.mailboxDelete(p);
        } catch (err) {
            console.warn(`${TAG} could not delete ${p}: ${err.responseText || err.message}`);
        }
    }
    for (const p of SPECIAL) {
        if (!existing.find(f => f.path === p)) {
            await client.mailboxCreate(p).catch(() => {});
        }
        const lock = await client.getMailboxLock(p);
        try {
            if (client.mailbox.exists > 0) {
                await client.messageDelete('1:*');
            }
        } finally {
            lock.release();
        }
    }

    // ---------------------------------------------------------------- 2. user folders (parent first)
    for (const [p, v] of Object.entries(MAILBOXES)) {
        if (!v.auto) {
            await client.mailboxCreate(p);
            await client.mailboxSubscribe(p);
        }
    }

    // ---------------------------------------------------------------- 3. append
    const fixtures = buildFixtures();
    const manifest = {
        description: 'Generated by scripts/seed.mjs - fixture inventory of the local iCloud-like test mailbox',
        account: ACCOUNT,
        // UIDVALIDITY/UIDNEXT are deliberately not stored: they change on every reset (use STATUS at runtime)
        mailboxes: {}
    };
    for (const [p, v] of Object.entries(MAILBOXES)) {
        manifest.mailboxes[p] = { specialUse: v.specialUse, count: 0, unseen: 0, messages: [] };
    }

    let notFresh = false;
    for (const f of fixtures) {
        const res = await client.append(f.mailbox, f.raw, f.flags, new Date(f.date));
        if (!res || !res.uid) throw new Error(`APPEND to ${f.mailbox} did not return APPENDUID (UIDPLUS missing?)`);
        const mb = manifest.mailboxes[f.mailbox];
        const parsed = await simpleParser(f.raw.split('\r\n\r\n')[0] + '\r\n\r\n', { skipHtmlToText: true, skipTextToHtml: true });
        const expectedUid = mb.messages.length + 1;
        if (res.uid !== expectedUid) notFresh = true;
        mb.messages.push({
            uid: res.uid,
            key: f.key,
            messageId: headerValue(f.raw, 'Message-ID'),
            subject: parsed.subject ?? null, // decoded (RFC 2047)
            from: parsed.from ? parsed.from.text : null,
            date: f.date,
            flags: f.flags,
            size: Buffer.byteLength(f.raw),
            note: f.note
        });
    }

    // ---------------------------------------------------------------- 4. verify counts with STATUS
    let ok = true;
    const runtime = {};
    for (const [p, mb] of Object.entries(manifest.mailboxes)) {
        const st = await client.status(p, { messages: true, unseen: true, uidNext: true, uidValidity: true });
        mb.count = st.messages;
        mb.unseen = st.unseen;
        runtime[p] = { uidValidity: String(st.uidValidity), uidNext: st.uidNext };
        if (st.messages !== mb.messages.length) {
            ok = false;
            console.error(`${TAG} count mismatch in ${p}: STATUS=${st.messages} appended=${mb.messages.length}`);
        }
    }
    await client.logout();

    fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
    fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');

    // ---------------------------------------------------------------- 5. report
    console.log(`${TAG} appended ${fixtures.length} messages; manifest -> ${path.relative(process.cwd(), MANIFEST) || MANIFEST}`);
    for (const [p, mb] of Object.entries(manifest.mailboxes)) {
        console.log(`${TAG}   ${p.padEnd(18)} messages=${String(mb.count).padStart(2)} unseen=${String(mb.unseen).padStart(2)} uidValidity=${runtime[p].uidValidity} uidNext=${runtime[p].uidNext}`);
    }
    if (notFresh) {
        console.warn(`${TAG} WARNING: mailboxes were not fresh, UIDs differ from the README inventory. Run ./reset.sh for canonical UIDs.`);
    }
    if (!ok) process.exit(1);
}

main().catch(err => {
    console.error(`${TAG} FAILED:`, err.responseText || err.message);
    if (err.code === 'ECONNREFUSED') console.error(`${TAG} is the server running? ./start.sh`);
    process.exit(1);
});
